function getProductCategory(equipment: Equipment): keyof typeof ENGLISH_KEYWORDS_EXPANDED {
  const id = equipment.id.toLowerCase();
  const name = equipment.name.toLowerCase();

  if (id.includes('esteira') || name.includes('esteira') || name.includes('treadmill')) return 'treadmill';
  if (id.includes('bicicleta') || id.includes('bike') || name.includes('bike')) return 'bike';
  if (id.includes('eliptico') || name.includes('elíptico') || name.includes('elliptical')) return 'elliptical';
  if (id.includes('escada') || name.includes('escada') || name.includes('stair')) return 'stairclimber';

  return 'strength';
}

/**
 * Mapeia categoria para chave em espanhol
 */
function getCategoryKeyEs(category: keyof typeof ENGLISH_KEYWORDS_EXPANDED): keyof typeof SPANISH_KEYWORDS_EXPANDED {
  const map: Record<string, keyof typeof SPANISH_KEYWORDS_EXPANDED> = {
    treadmill: 'caminadora',
    bike: 'bicicleta',
    elliptical: 'eliptica',
    stairclimber: 'escaladora',
    strength: 'musculacion',
  };
  return map[category] || 'musculacion';
}

/**
 * Gera keywords expandidas internacionais baseado no idioma
 */
export function generateExpandedInternationalKeywords(
  equipment: Equipment,
  locale: 'en' | 'es'
): SEOKeyword[] {
  const category = getProductCategory(equipment);
  
  let keywords: string[] = [];

  if (locale === 'en') {
    keywords = ENGLISH_KEYWORDS_EXPANDED[category] || [];
  } else if (locale === 'es') {
    const spanishCategory = getCategoryKeyEs(category);
    keywords = SPANISH_KEYWORDS_EXPANDED[spanishCategory] || [];
  } else {
    return [];
  }

  return keywords.map((keyword, index) => {
    // Determine type
    let type: 'primary' | 'secondary' | 'long-tail' = 'long-tail';
    if (index < 20) type = 'primary';
    else if (index < 50) type = 'secondary';

    // Determine search intent
    let searchIntent: 'commercial' | 'transactional' | 'informational' = 'commercial';
    const lowerKeyword = keyword.toLowerCase();
    
    if (
      lowerKeyword.includes('buy') ||
      lowerKeyword.includes('price') ||
      lowerKeyword.includes('comprar') ||
      lowerKeyword.includes('precio') ||
      lowerKeyword.includes('need') ||
      lowerKeyword.includes('want') ||
      lowerKeyword.includes('necesito') ||
      lowerKeyword.includes('quiero')
    ) {
      searchIntent = 'transactional';
    } else if (
      lowerKeyword.includes('how') ||
      lowerKeyword.includes('what') ||
      lowerKeyword.includes('which') ||
      lowerKeyword.includes('cómo') ||
      lowerKeyword.includes('cuál') ||
      lowerKeyword.includes('qué')
    ) {
      searchIntent = 'informational';
    }

    // Determine priority
    let priority = 7;
    if (index < 10) priority = 10;
    else if (index < 25) priority = 9;
    else if (index < 50) priority = 8;

    return {
      keyword,
      type,
      searchIntent,
      priority,
    };
  });
}

