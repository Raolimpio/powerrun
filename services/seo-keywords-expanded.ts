/**
 * Identifica categoria do produto
 */
function getProductCategory(equipment: Equipment): keyof typeof REGIONAL_KEYWORDS_BR {
  const id = equipment.id.toLowerCase();
  const name = equipment.name.toLowerCase();

  if (id.includes('esteira') || name.includes('esteira')) return 'esteira';
  if (id.includes('bicicleta') || id.includes('bike') || name.includes('bike')) return 'bicicleta';
  if (id.includes('eliptico') || name.includes('elíptico') || name.includes('elliptical')) return 'eliptico';
  if (id.includes('escada') || name.includes('escada') || name.includes('stair')) return 'escada';

  return 'musculacao';
}

/**
 * Gera keywords expandidas para um produto (30-50 keywords)
 */
export function generateExpandedKeywords(equipment: Equipment): SEOKeyword[] {
  // Validar entrada
  if (!equipment || !equipment.name) {
    console.warn('[generateExpandedKeywords] Equipment inválido:', equipment);
    return [];
  }

  const category = getProductCategory(equipment);
  
  const keywords: SEOKeyword[] = [];

  // 1. Keywords regionais (20-25 keywords)
  const regionalKeywords = REGIONAL_KEYWORDS_BR[category] || [];
  regionalKeywords.forEach((keyword, index) => {
    keywords.push({
      keyword,
      type: index < 10 ? 'primary' : index < 20 ? 'secondary' : 'long-tail',
      searchIntent: keyword.includes('preço') || keyword.includes('comprar') || keyword.includes('onde')
        ? 'transactional'
        : keyword.includes('fabricante') || keyword.includes('distribuidor') || keyword.includes('revenda')
        ? 'commercial'
        : keyword.includes('como') || keyword.includes('qual') || keyword.includes('diferença')
        ? 'informational'
        : 'commercial',
      priority: index < 5 ? 10 : index < 12 ? 9 : index < 20 ? 8 : 7,
    });
  });

  // 2. Keywords de concorrentes (5-8 keywords)
  const competitorKeywords = COMPETITOR_KEYWORDS[category] || [];
  competitorKeywords.forEach((keyword) => {
    keywords.push({
      keyword,
      type: 'secondary',
      searchIntent: 'commercial',
      priority: 7,
    });
  });

  // 3. Keywords de nicho (10-15 keywords)
  const nicheKeywords = NICHE_KEYWORDS[category] || [];
  nicheKeywords.forEach((keyword, index) => {
    keywords.push({
      keyword,
      type: 'long-tail',
      searchIntent: 'commercial',
      priority: index < 5 ? 8 : 6,
    });
  });

  // 4. Keywords com nome do produto (3-5 keywords)
  const productName = equipment.name.toLowerCase();
  keywords.push(
    {
      keyword: productName,
      type: 'primary',
      searchIntent: 'navigational',
      priority: 10,
    },
    {
      keyword: `${productName} preço`,
      type: 'long-tail',
      searchIntent: 'transactional',
      priority: 9,
    },
    {
      keyword: `onde comprar ${productName}`,
      type: 'long-tail',
      searchIntent: 'transactional',
      priority: 8,
    },
    {
      keyword: `${productName} para academia`,
      type: 'secondary',
      searchIntent: 'commercial',
      priority: 8,
    },
    {
      keyword: `melhor ${productName}`,
      type: 'long-tail',
      searchIntent: 'informational',
      priority: 7,
    }
  );

  // Remover duplicatas e ordenar por prioridade
  const uniqueKeywords = Array.from(
    new Map(keywords.map(k => [k.keyword, k])).values()
  ).sort((a, b) => b.priority - a.priority);

  return uniqueKeywords;
}

