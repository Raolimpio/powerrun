// === 🔧 FUNÇÃO HELPER ===
export function getPDFsForEquipment(equipmentId: string) {
  return equipmentPDFs[equipmentId as keyof typeof equipmentPDFs] || { manual: '', ficha: '' };
}

export function hasDocuments(equipmentId: string): boolean {
  const pdfs = getPDFsForEquipment(equipmentId);
  return Boolean(pdfs && (pdfs.manual || pdfs.ficha));
}
